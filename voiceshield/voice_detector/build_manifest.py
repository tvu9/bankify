#!/usr/bin/env python3
"""Bootstrap a labeled dataset CSV from user-supplied directories, without inventing splits.

Use different, source/speaker-disjoint collections for validation and test.
Hand-edit speaker_id/source_id/generator_id based on verified recording provenance.
"""
import argparse
import hashlib
from pathlib import Path
try: from .v3_common import FIELDS, write_csv
except ImportError: from v3_common import FIELDS, write_csv


def build(real_dir,fake_dir,split):
    result=[]
    for label,dir_ in [('real',real_dir),('fake',fake_dir)]:
        root=Path(dir_).expanduser().resolve()
        if not root.is_dir(): raise FileNotFoundError(root)
        paths=sorted(p for p in root.rglob('*') if p.is_file() and p.suffix.lower() in ('.wav','.flac','.ogg'))
        if not paths: raise ValueError(f'No audio files in {root}')
        for p in paths:
            # Provenance of original recordings must still be checked by the user.
            key=hashlib.sha256(str(p).encode()).hexdigest()[:16]
            result.append({'sample_id':f'{split}_{label}_{key}','path':str(p),'label':label,
                           'split':split,'source_id':f'REVIEW_{key}',
                           'speaker_id':'','generator_id':'','channel':'original','license':''})
    return result


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--real-dir',required=True)
    p.add_argument('--fake-dir',required=True)
    p.add_argument('--split',required=True,choices=['train','val','test'])
    p.add_argument('--out',required=True)
    args=p.parse_args()
    result=build(args.real_dir,args.fake_dir,args.split)
    write_csv(args.out,result,FIELDS)
    print(f'Created {len(result)} labeled rows in {args.out}. IMPORTANT: review source_id, speaker_id, generator_id, and license.')
    print('Do not use this autogenerated manifest for final evaluation until you have checked speaker/source leakage.')

if __name__=='__main__': main()
